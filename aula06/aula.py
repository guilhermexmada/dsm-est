# medidas centrais dos dados

# tendência central = medida que busca representar um conjunto de dados através de 1 único valor

# Média Aritmética = soma de todos os valores dividida pela quantidade dos dados
# Média Ponderada = soma dos produtos dos dados pelos seus respectivos pesos, dividida pela soma dos pesos
# Mediana = valor da posição central quando os valores estão ordenados (em casos de quantidade par, é a média dos 2 elementos centrais)
# Moda = valor que aparece com maior frequência no conjunto de dados

# A média foca num ponto de equilíbrio dos dados
# A mediana é o "meio do conjunto", sendo roubsta contra outliers (valores muito discrepantes)
# A moda é excelente para dados categórios (que não são numéricos)

# unimodal = 1 moda; bimodal = 2 modas; multimodal = 3+ modas; amodal = nenhuma moda